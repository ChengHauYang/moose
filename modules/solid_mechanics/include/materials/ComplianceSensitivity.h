#pragma once

#include "StrainEnergyDensity.h"
#include "MathUtils.h"

/**
 * Computes the elasticity compliance sensitivity with respect to a user-supplied variable.
 */
template <bool is_ad>
class ComplianceSensitivityTempl : public StrainEnergyDensityTempl<is_ad>
{
public:
  static InputParameters validParams();

  ComplianceSensitivityTempl(const InputParameters & parameters);

  virtual void computeQpProperties() override;

protected:
  /// Sensitivity material generated by this object
  GenericMaterialProperty<Real, is_ad> & _sensitivity;
  /// Pseudo-density variable
  const GenericVariableValue<is_ad> & _design_density;
  /// Pseudo-density variable name
  const MaterialPropertyName _design_density_name;
  /// Derivative of elasticity modulus with respect to pseudo-density
  const GenericMaterialProperty<Real, is_ad> & _dEdp;
  /// Young's modulus of the material
  const GenericMaterialProperty<Real, is_ad> & _youngs_modulus;

  using StrainEnergyDensityTempl<is_ad>::_base_name;
  using StrainEnergyDensityTempl<is_ad>::_strain_energy_density;
  using Material::_qp;
};

using ComplianceSensitivity = ComplianceSensitivityTempl<false>;
using ADComplianceSensitivity = ComplianceSensitivityTempl<true>;
