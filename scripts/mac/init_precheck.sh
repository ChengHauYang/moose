#!/usr/bin/env bash
set -eo pipefail

# Install the pre-commit hook for this clone. Hooks live in .git/hooks, which is
# per-clone and never cloned or pushed, so each checkout needs this once.

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
source "$SCRIPT_DIR/moose_mac_common.sh"

moose_mac_locate_repo

set -u

moose_mac_section "Installing pre-commit hook"
echo "Repository: $MOOSE_DIR"

if [[ ! -f "$MOOSE_DIR/.pre-commit-config.yaml" ]]; then
    moose_mac_die "No .pre-commit-config.yaml in $MOOSE_DIR; nothing to install."
fi

# pre-commit lives in the miniforge base environment rather than the moose
# environment, so pick the first interpreter that can import it instead of
# activating a Conda environment.
PYTHON=""
for candidate in "$HOME/miniforge/bin/python3" python3; do
    if command -v "$candidate" >/dev/null 2>&1 && "$candidate" -c 'import pre_commit' 2>/dev/null; then
        PYTHON="$candidate"
        break
    fi
done

if [[ -z "$PYTHON" ]]; then
    moose_mac_die "pre-commit is not importable. Install it with: $HOME/miniforge/bin/python3 -m pip install pre-commit"
fi

# An installed hook hardcodes the interpreter path, so one left behind by a
# deleted Conda environment is stale, not merely switched off. Reinstalling
# below rewrites it; drop any renamed copy so it cannot be revived by hand.
DISABLED_HOOK="$(git -C "$MOOSE_DIR" rev-parse --git-path hooks/pre-commit.disabled)"
if [[ -f "$DISABLED_HOOK" ]] && grep -q 'generated by pre-commit' "$DISABLED_HOOK"; then
    rm -f "$DISABLED_HOOK"
    echo "Removed stale $DISABLED_HOOK"
fi

cd "$MOOSE_DIR"
"$PYTHON" -m pre_commit install

HOOK="$(git -C "$MOOSE_DIR" rev-parse --git-path hooks/pre-commit)"

echo
echo "HOOK=$HOOK"
echo "PYTHON=$PYTHON"
echo "PRECHECK_INSTALLED=1"
